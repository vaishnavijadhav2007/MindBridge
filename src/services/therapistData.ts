/**
 * Strict validator to guarantee that any listing displayed belongs strictly to Pune district, Maharashtra.
 */
export function isVerifiedInPuneDistrict(therapist: PuneTherapist): boolean {
  if (!therapist.isDistrictVerified) return false;
  if (therapist.district !== 'Pune District, Maharashtra') return false;
  return PUNE_LOCALITIES.includes(therapist.locality);
}

